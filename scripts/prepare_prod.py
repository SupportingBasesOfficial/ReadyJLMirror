"""
JLMirror — Production secrets generator + realm patcher.

Run once before the first deploy to generate all required secrets and
update the Keycloak realm JSON with the production domain.

Usage:
    python scripts/prepare_prod.py \
        --domain mirror.jlinformatica.com.br \
        --kc-domain auth.jlinformatica.com.br \
        --email mauricio@jlinformatica.com.br \
        --zabbix zabbix.jlinformatica.com.br

Output:
    .env               — production environment file (fill BAO_TOKEN after first boot)
    docker/keycloak/realm-jlmirror.json — patched with production URLs + new secret
"""

import argparse

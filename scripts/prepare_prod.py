from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent


def strong_password(n: int = 32) -> str:
    return secrets.token_urlsafe(n)


def generate_vapid_keys() -> tuple[str, str]:
    try:
        from cryptography.hazmat.primitives.asymmetric.ec import (
            SECP256R1,
            generate_private_key,
        )
        from cryptography.hazmat.primitives.serialization import (
            Encoding,
            NoEncryption,
            PrivateFormat,
            PublicFormat,
        )
        import base64

        k = generate_private_key(SECP256R1())
        priv = base64.urlsafe_b64encode(
            k.private_bytes(Encoding.DER, PrivateFormat.PKCS8, NoEncryption())
        ).rstrip(b"=").decode()
        pub = base64.urlsafe_b64encode(
            k.public_key().public_bytes(Encoding.X962, PublicFormat.UncompressedPoint)
        ).rstrip(b"=").decode()
        return priv, pub
    except ImportError:
        print("  [aviso] cryptography não instalado — VAPID keys marcadas como TODO")
        return "TODO_gerar_com_cryptography", "TODO_gerar_com_cryptography"


def patch_realm(kc_secret: str, public_domain: str) -> None:
    realm_path = BASE_DIR / "docker" / "keycloak" / "realm-jlmirror.json"
    with open(realm_path) as f:
        realm = json.load(f)

    prod_origin = f"https://{public_domain}"
    prod_uri = f"https://{public_domain}/*"

    for client in realm.get("clients", []):
        if client.get("clientId") != "jlmirror-bff":
            continue
        # Update client secret
        client["secret"] = kc_secret
        # Replace placeholder redirect URIs
        client["redirectUris"] = [
            uri.replace("https://REPLACE_WITH_PROD_HOSTNAME", prod_origin)
            if "REPLACE_WITH_PROD_HOSTNAME" in uri
            else uri
            for uri in client.get("redirectUris", [])
        ]
        if prod_uri not in client["redirectUris"]:
            client["redirectUris"].append(prod_uri)
        # Replace placeholder web origins
        client["webOrigins"] = [
            o.replace("https://REPLACE_WITH_PROD_HOSTNAME", prod_origin)
            if "REPLACE_WITH_PROD_HOSTNAME" in o
            else o
            for o in client.get("webOrigins", [])
        ]
        if prod_origin not in client["webOrigins"]:
            client["webOrigins"].append(prod_origin)

    with open(realm_path, "w") as f:
        json.dump(realm, f, indent=2, ensure_ascii=False)
    print(f"  ✓  {realm_path.relative_to(BASE_DIR)} atualizado")


def write_env(values: dict[str, str]) -> None:
    env_path = BASE_DIR / ".env"
    if env_path.exists():
        print(f"\n  [aviso] .env já existe — salvando em .env.generated para não sobrescrever.")
        env_path = BASE_DIR / ".env.generated"

    lines = [
        "# JLMirror — generated by scripts/prepare_prod.py",
        "# Revise e mova para .env antes de rodar deploy.sh",
        "# Após o primeiro boot, adicione BAO_TOKEN conforme instrução do deploy.sh",
        "",
    ]
    for k, v in values.items():
        if k.startswith("#"):
            lines.append(f"\n# {v}")
        else:
            lines.append(f"{k}={v}")

    env_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  ✓  {env_path.name} gravado")


